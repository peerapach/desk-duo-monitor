// Convert the approved transparent source into four bounded, flash-resident images.
// Run with Node; SHARP_PATH may override the sharp module path for portability.
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const sharp = require(process.env.SHARP_PATH || path.join(path.dirname(process.execPath), '../node_modules/sharp'));
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const previews = process.argv.indexOf('--preview-dir');
const previewDir = previews >= 0 ? path.resolve(process.argv[previews + 1]) : null;
if (previewDir) await fs.mkdir(previewDir, { recursive: true });
let output = '// Generated by scripts/compile_character_assets.mjs. RGB565, little-endian, black background.\n';
for (const [provider, name] of ['claude', 'codex'].entries()) {
  const source = path.join(root, `firmware/assets/${provider ? 'codex-logo' : 'claude-approved'}.png`);
  const {data, info}=await sharp(source).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  let left = info.width, right = -1, top = info.height, bottom = -1;
  for (let y = 0; y < info.height; ++y) for (let x = 0; x < info.width; ++x) {
    // Ignore isolated alpha=1 extraction noise when finding visible bounds.
    if (data[(y * info.width + x) * 4 + 3] <= 1) continue;
    left = Math.min(left, x); right = Math.max(right, x);
    top = Math.min(top, y); bottom = Math.max(bottom, y);
  }
  if (right < left) throw new Error(`No nontransparent ${name} pixels`);
  for (const size of [64, 32]) {
    const { data: rgb } = await sharp(source)
      .extract({ left, top, width: right - left + 1, height: bottom - top + 1 })
      .resize(size, size, { fit: 'contain', background: '#000000', kernel: 'lanczos3' })
      .flatten({ background: '#000000' }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
    const bytes = Buffer.alloc(size * size * 2), decoded = Buffer.alloc(size * size * 3);
    for (let i = 0; i < size * size; ++i) {
      const r = rgb[i * 3], g = rgb[i * 3 + 1], b = rgb[i * 3 + 2];
      const rgb565 = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
      bytes.writeUInt16LE(rgb565, i * 2);
      decoded[i * 3] = Math.round((rgb565 >> 11) * 255 / 31);
      decoded[i * 3 + 1] = Math.round(((rgb565 >> 5) & 63) * 255 / 63);
      decoded[i * 3 + 2] = Math.round((rgb565 & 31) * 255 / 31);
    }
    output += `alignas(4) const uint8_t ${name}_${size}[] = {\n`;
    for (let i = 0; i < bytes.length; i += 24) {
      output += '    ' + [...bytes.subarray(i, i + 24)].map(b => `0x${b.toString(16).padStart(2, '0')}`).join(',') + ',\n';
    }
    output += '};\n';
    if (previewDir) await sharp(decoded, { raw: { width: size, height: size, channels: 3 } })
      .png().toFile(path.join(previewDir, `${name}-${size}.png`));
    console.log(`${name} ${size}x${size}: ${bytes.length} bytes, source bounds ${left},${top}..${right},${bottom}`);
  }
}
await fs.mkdir(path.join(root, 'firmware/main/generated'), { recursive: true });
await fs.writeFile(path.join(root, 'firmware/main/generated/character_pixels.inc'), output);
