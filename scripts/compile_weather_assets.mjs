// Compile the approved 3×2 atlas to six 96px and six 28px flash-resident RGB565 images.
// Run with Node; SHARP_PATH may override the sharp module path for portability.
import fs from 'node:fs/promises';
import { weatherTileRegion, weatherArtworkSource, weatherForecastSource, weatherBlackMatte, weatherArtworkPixels } from './weather_artwork.mjs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const sharp = require(process.env.SHARP_PATH || path.join(path.dirname(process.execPath), '../node_modules/sharp'));
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const previews = process.argv.indexOf('--preview-dir');
const previewDir = previews >= 0 ? path.resolve(process.argv[previews + 1]) : null;
if (previewDir) await fs.mkdir(previewDir, { recursive: true });
// Forecast symbols follow the approved simple cloud/rain silhouettes rather than downsampling hero detail.
function forecastSvg(tile) {
  const sunny=tile===0||tile===1, moon=tile===2||tile===3, cloud=tile!==0&&tile!==2, rain=tile===5;
  return Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="28" height="28" viewBox="0 0 28 28"><defs><linearGradient id="c" x1="0" y1="0" x2="0" y2="1"><stop stop-color="#f1f1eb"/><stop offset=".55" stop-color="#babdb9"/><stop offset="1" stop-color="#787f7c"/></linearGradient><radialGradient id="s"><stop stop-color="#fff6cd"/><stop offset="1" stop-color="#e8b970"/></radialGradient></defs>${sunny?`<circle cx="${cloud?19:14}" cy="${cloud?9:13}" r="${cloud?6:9}" fill="url(#s)"/>`:''}${moon?`<path d="M17 3a10 10 0 1 0 7 15A11 11 0 0 1 17 3" fill="#eee1bd"/>`:''}${cloud?`<path d="M6 21C0 21 0 13 6 13C6 5 17 4 19 11C26 8 29 21 22 21Z" fill="url(#c)"/>`:''}${rain?'<path d="M8 24l-1 2m8-2l-1 2m8-2l-1 2" stroke="#8ae4cc" stroke-width="1.6" stroke-linecap="round"/>':''}</svg>`);
}
let output = '// Generated by scripts/compile_weather_assets.mjs. RGB565, little-endian, black background.\n';
for (let tile=0;tile<6;++tile) {
  const name=`weather_${tile}`;
  const selection=weatherArtworkSource(tile);
  const source = path.join(root, selection.path);
  const {data,info}=await sharp(source).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  const region=weatherTileRegion(data,info.width,info.height,selection.atlasTile);
  const {left,top,width,height}=region;
  for (const size of [96, 28]) {
    const miniSource=weatherForecastSource(tile);
    let artwork;
    if(size===28 && miniSource) {
      const miniPath=path.join(root,miniSource), mini=await sharp(miniPath).ensureAlpha().raw().toBuffer({resolveWithObject:true});
      artwork=sharp(Buffer.from(weatherBlackMatte(mini.data)),{raw:{width:mini.info.width,height:mini.info.height,channels:4}}).extract(weatherTileRegion(mini.data,mini.info.width,mini.info.height,null));
    } else artwork=size===28?sharp(forecastSvg(tile)):sharp(Buffer.from(weatherArtworkPixels(data,info.width,tile)),{raw:{width:info.width,height:info.height,channels:4}}).extract(region);
    const { data: rgb } = await artwork
      .resize(size, size, { fit: 'contain', background: '#000000', kernel: 'lanczos3' })
      .flatten({ background: '#000000' }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
    const bytes = Buffer.alloc(size * size * 2), decoded = Buffer.alloc(size * size * 3);
    for (let i = 0; i < size * size; ++i) {
      const r = rgb[i * 3], g = rgb[i * 3 + 1], b = rgb[i * 3 + 2];
      const rgb565 = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
      bytes.writeUInt16LE(rgb565, i * 2);
      decoded[i * 3] = Math.round((rgb565 >> 11) * 255 / 31);
      decoded[i * 3 + 1] = Math.round(((rgb565 >> 5) & 63) * 255 / 63);
      decoded[i * 3 + 2] = Math.round((rgb565 & 31) * 255 / 31);
    }
    output += `alignas(4) const uint8_t ${name}_${size}[] = {\n`;
    for (let i = 0; i < bytes.length; i += 24) {
      output += '    ' + [...bytes.subarray(i, i + 24)].map(b => `0x${b.toString(16).padStart(2, '0')}`).join(',') + ',\n';
    }
    output += '};\n';
    if (previewDir) await sharp(decoded, { raw: { width: size, height: size, channels: 3 } })
      .png().toFile(path.join(previewDir, `${name}-${size}.png`));
    console.log(`${name} ${size}x${size}: ${bytes.length} bytes, source bounds ${left},${top}..${left+width-1},${top+height-1}`);
  }
}
// Navigation is a compact, antialiased outline asset; black pixels match the device background.
const navPaths=[
  '<circle cx="9" cy="5" r="3.2"/><path d="M2 20v-1a7 7 0 0 1 14 0v1Z M15 2a3 3 0 0 1 0 6 M17 11a6 6 0 0 1 5 6v3h-4"/>',
  '<path d="M6 18a4.5 4.5 0 0 1-.6-9 6.5 6.5 0 0 1 12.5-1.5A5.3 5.3 0 0 1 19 18Z"/>',
  '<path d="M5 20v-6 M12 20V9 M19 20V3"/>',
  '<path d="M2 5h4m4 0h12 M2 11h12m4 0h4 M2 17h5m4 0h11"/><circle cx="8" cy="5" r="2"/><circle cx="16" cy="11" r="2"/><circle cx="9" cy="17" r="2"/>'
];
for(let tab=0;tab<4;tab++)for(let active=0;active<2;active++){
  const svg=Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="24" height="22" viewBox="0 0 24 22"><g fill="none" stroke="${active?'#f0f1ea':'#a3aaa8'}" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">${navPaths[tab]}</g></svg>`);
  const rgb=await sharp(svg).flatten({background:'#000'}).removeAlpha().raw().toBuffer(),bytes=Buffer.alloc(24*22*2);
  for(let i=0;i<24*22;i++)bytes.writeUInt16LE(((rgb[i*3]>>3)<<11)|((rgb[i*3+1]>>2)<<5)|(rgb[i*3+2]>>3),i*2);
  output+=`alignas(4) const uint8_t navigation_${tab}_${active}[] = {\n`;
  for(let i=0;i<bytes.length;i+=24)output+='    '+[...bytes.subarray(i,i+24)].map(b=>`0x${b.toString(16).padStart(2,'0')}`).join(',')+',\n';
  output+='};\n';
}
await fs.mkdir(path.join(root, 'firmware/main/generated'), { recursive: true });
await fs.writeFile(path.join(root, 'firmware/main/generated/weather_pixels.inc'), output);
