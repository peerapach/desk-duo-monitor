#!/usr/bin/env python3
"""Reproduce DeskDuo's compact LVGL Thai fonts (Pillow/FreeType + fontTools).

No runtime shaping dependency. Existing U+F700..F719 IDs are preserved;
F71A/B provide descenderless bases and F720..F765 contextual tone forms.
"""
import argparse
import hashlib
import json
import io
import subprocess
import shutil
from functools import lru_cache
from pathlib import Path

from PIL import Image, ImageFont
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / "firmware/main/fonts"
ABOVE = [0xE31, *range(0xE34, 0xE38), 0xE47, 0xE4D, 0xE4E]
TONES = list(range(0xE48, 0xE4D))
BELOW = list(range(0xE38, 0xE3B))
MARKS = ABOVE + TONES + BELOW
CONTEXT_ABOVE = [cp for cp in ABOVE if cp != 0xE35]
RANGES = [(0xE01, 58), (0xE3F, 29), (0xF700, 28), (0xF720, 70)]


@lru_cache(None)
def shape_source(source, text):
    hb = shutil.which("hb-shape") or "/opt/homebrew/bin/hb-shape"
    command = [hb, "--output-format=json", "--font-size=upem", "--shapers=ot",
               "--language=th", "--script=Thai", str(source), text]
    return json.loads(subprocess.check_output(command))


def generate(size, ui=False, numeric=False):
    weight = "SemiBold" if size == 18 or ui or numeric else "Medium"
    source = FONT_DIR / "source" / f"Sarabun-{weight}.ttf"
    tt = TTFont(source)
    cmap = tt.getBestCmap()
    scale = size / tt["head"].unitsPerEm
    # HarfBuzz is an offline authoring oracle, never linked into firmware.
    # Map glyph names to private Unicode only in an in-memory authoring font.
    # This lets FreeType rasterize actual GSUB-selected alternate outlines.
    mapped = {name: 0xE000 + n for n, name in enumerate(tt.getGlyphOrder())}
    for table in tt["cmap"].tables:
        if table.isUnicode():
            table.cmap.update({cp: name for name, cp in mapped.items()})
    memory = io.BytesIO()
    tt.save(memory)
    memory.seek(0)
    font = ImageFont.truetype(memory, size, layout_engine=ImageFont.Layout.BASIC)
    data = bytearray()
    glyphs = {}
    bitmap_cache = {}

    def raster(cp, name, dx=0, dy=0, mark=True):
        mask, offset = font.getmask2(chr(mapped[name]), anchor="ls")
        image = Image.frombytes("L", mask.size, bytes(mask))
        bounds = image.getbbox()
        assert bounds is not None or cp == 32, f"Missing source outline {name}"
        if bounds is not None:
            image = image.crop(bounds)
        else:
            image = Image.new("L", (0,0))
            bounds = (0,0,0,0)
        w, h = image.size
        x, top = offset[0] + bounds[0], offset[1] + bounds[1]
        pixels = [(p * 15 + 127) // 255 for p in image.tobytes()]
        if len(pixels) % 2:
            pixels.append(0)
        packed = bytes((pixels[i] << 4) | pixels[i+1] for i in range(0,len(pixels),2))
        key = (w, h, packed)
        if key not in bitmap_cache:
            bitmap_cache[key] = len(data)
            data.extend(packed)
        glyphs[cp] = dict(bitmap_index=bitmap_cache[key],
            adv_w=0 if mark else round(font.getlength(chr(mapped[name])) * 16),
            box_w=w, box_h=h, ofs_x=x+round(dx*scale),
            ofs_y=-top-h+round(dy*scale))

    def context(cp, text, index=-1, mark=True):
        glyph = shape_source(str(source), text)[index]
        raster(cp, glyph["g"], glyph["dx"], glyph["dy"], mark)

    if ui:
        for cp in [*range(32,127),176]:
            raster(cp,cmap[cp],mark=False)
    if numeric:
        for cp in sorted(map(ord," %+-.0123456789")):
            raster(cp,cmap[cp],mark=False)
    else:
        for cp in [*range(0xE01,0xE3B), *range(0xE3F,0xE5C)]:
            raster(cp, cmap[cp], mark=cp in MARKS)
        for n, cp in enumerate(ABOVE):
            context(0xF700+n, "ป"+chr(cp))
        for n, cp in enumerate(TONES):
            context(0xF708+n, "ป"+chr(cp))
            context(0xF70D+n, "กี"+chr(cp))
            context(0xF712+n, "ปี"+chr(cp))
        for n, cp in enumerate(BELOW):
            context(0xF717+n, "ญ"+chr(cp))
        context(0xF71A, "ญุ", index=0, mark=False)
        context(0xF71B, "ฐู", index=0, mark=False)
        for n, above in enumerate(CONTEXT_ABOVE):
            for tall, base in enumerate(("ก","ป")):
                for k,tone in enumerate(TONES):
                    context(0xF720+n*10+tall*5+k, base+chr(above)+chr(tone))
    top = max(g["ofs_y"] + g["box_h"] for g in glyphs.values())
    bottom = min(g["ofs_y"] for g in glyphs.values())
    line_height, base_line = top - bottom + 2, -bottom + 1
    name = f"ct_font_numeric_{size}" if numeric else f"ct_font_ui_{size}" if ui else f"ct_font_thai_{size}"
    ranges = ([(32,95),(176,1)] if ui else []) + RANGES
    lines = [f"/* Generated by scripts/export_thai_fonts.py; Sarabun {weight} {size}px, OFL-1.1.",
             f" * Source SHA256 {hashlib.sha256(source.read_bytes()).hexdigest()}",
             " * 4bpp, proportional FreeType advances; PUA shaping contract: assets.hpp. */", '#include "lvgl.h"',
             f"static LV_ATTRIBUTE_LARGE_CONST const uint8_t {name}_bitmap[] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{v:02x}" for v in data[i:i+24]) + ",")
    lines += ["};", f"static const lv_font_fmt_txt_glyph_dsc_t {name}_dsc[] = {{", "    {0}, /* reserved */"]
    for cp, glyph in sorted(glyphs.items()):
        fields = ", ".join(f".{k} = {v}" for k, v in glyph.items())
        lines.append(f"    {{{fields}}}, /* U+{cp:04X} */")
    lines.append("};")
    if numeric:
        offsets = [cp-32 for cp in sorted(glyphs)]
        lines.append(f"static const uint16_t {name}_unicode[] = {{" + ", ".join(map(str,offsets)) + "};")
    lines.append(f"static const lv_font_fmt_txt_cmap_t {name}_cmaps[] = {{")
    gid = 1
    for start, length in ([] if numeric else ranges):
        lines.append(f"    {{.range_start = {start}, .range_length = {length}, .glyph_id_start = {gid}, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}},")
        gid += length
    if numeric:
        lines.append(f"    {{.range_start = 32, .range_length = 26, .glyph_id_start = 1, .unicode_list = {name}_unicode, .list_length = {len(glyphs)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}},")
    lines += ["};", f"static const lv_font_fmt_txt_dsc_t {name}_font_dsc = {{",
              f"    .glyph_bitmap = {name}_bitmap, .glyph_dsc = {name}_dsc, .cmaps = {name}_cmaps,",
              f"    .cmap_num = {1 if numeric else len(ranges)}, .bpp = 4,", "};", f"const lv_font_t {name} = {{",
              "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
              f"    .line_height = {line_height}, .base_line = {base_line}, .subpx = LV_FONT_SUBPX_NONE,",
              f"    .underline_position = -1, .underline_thickness = 1, .dsc = &{name}_font_dsc,", "};", ""]
    return "\n".join(lines), glyphs, len(data), line_height, base_line


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify committed output is reproducible")
    args = parser.parse_args()
    summary = {}
    for size in (12, 14, 18):
        text, glyphs, bitmap_bytes, height, baseline = generate(size)
        path = FONT_DIR / f"ct_font_thai_{size}.c"
        if args.check:
            assert path.read_text() == text, f"Stale generated font: {path}"
        else:
            path.write_text(text)
        assert len({g["adv_w"] for cp, g in glyphs.items() if 0xE01 <= cp <= 0xE2E}) >= 4
        assert all(glyphs[cp]["adv_w"] == 0 for cp in MARKS + list(range(0xF700, 0xF71A)) + list(range(0xF720,0xF766)))
        assert size != 18 or glyphs[0xE01]["box_h"] >= 10
        for n, cp in enumerate(TONES):
            assert glyphs[0xF70D+n]["bitmap_index"] != glyphs[cp]["bitmap_index"]
            assert glyphs[0xF70D+n]["ofs_y"] > glyphs[cp]["ofs_y"]
            assert glyphs[0xF712+n]["ofs_x"] < glyphs[0xF70D+n]["ofs_x"]
        assert glyphs[0xF71A]["box_h"] < glyphs[0xE0D]["box_h"]
        assert glyphs[0xF71B]["box_h"] < glyphs[0xE10]["box_h"]
        assert all(0 <= baseline + g["ofs_y"] and
                   baseline + g["ofs_y"] + g["box_h"] < height for g in glyphs.values())
        summary[size] = dict(bitmap_bytes=bitmap_bytes, line_height=height, base_line=baseline,
                             body_height=glyphs[0xE01]["box_h"])
    for size, ui, numeric in ((16,True,False),(18,True,False),(24,False,True),(48,False,True)):
        text, glyphs, bitmap_bytes, height, baseline = generate(size,ui=ui,numeric=numeric)
        name = f"ct_font_ui_{size}" if ui else f"ct_font_numeric_{size}"
        path = FONT_DIR / f"{name}.c"
        if args.check:
            assert path.read_text() == text, f"Stale generated font: {path}"
        else:
            path.write_text(text)
        assert glyphs[32]["adv_w"] > 0
        assert glyphs[32]["box_w"] == glyphs[32]["box_h"] == 0
        assert all(g["bitmap_index"] + (g["box_w"]*g["box_h"]+1)//2 <= bitmap_bytes for g in glyphs.values())
        assert all(0 <= baseline + g["ofs_y"] and
                   baseline + g["ofs_y"] + g["box_h"] < height for g in glyphs.values())
        if numeric:
            assert sorted(glyphs) == sorted(map(ord," %+-.0123456789"))
        else:
            assert all(cp in glyphs for cp in [*range(32,127),176])
            assert all(glyphs[cp]["adv_w"] == 0 for cp in MARKS + list(range(0xF700,0xF71A)) + list(range(0xF720,0xF766)))
        summary[name] = dict(bitmap_bytes=bitmap_bytes,line_height=height,base_line=baseline,
                            digit_height=glyphs[ord("0")]["box_h"])
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
